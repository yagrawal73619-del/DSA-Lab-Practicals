class Task3 {
    public static void main(String[] args) {
        int[] a = {52, 10, 52, 7, 52};
        int count = 0;

        for (int i = 0; i < a.length; i++) {
            if (a[i] == 52) {
                count++;
            }
        }

        System.out.println("Count: " + count);
    }
}